import csv
import json
import statistics
from collections import defaultdict

from compare import PAGE_METRICS, TABLE_METRICS
from ocr_to_md import ROOT

RESULTS = ROOT / "results"
LABELS = {
    "E-002": "test baseline", "E-004": "dev baseline", "E-005": "dev, I-1 loop repair",
    "E-006": "test, I-1 loop repair", "E-007": "test, I-1 + I-6 marker repair",
    "E-011": "dev, 8-bit", "E-012": "dev, 8-bit + I-1 (8-bit retry)", "E-013": "dev, 8-bit + I-1 (bf16 fallback)", "E-014": "dev, 4-bit", "E-015": "dev, 4-bit + I-1 (bf16 fallback)", "E-016": "dev, 4 experts per token",
    "E-017": "dev, 8-bit + 4 experts", "E-018": "dev, 8-bit + 4 experts + I-1 (bf16 fallback)",
}
METRIC_NAMES = {"text_block": "Text Edit", "reading_order": "R-order Edit", "table_TEDS": "TEDS", "table_TEDS_S": "TEDS-S"}


def interval_cell(stat, digits):
    lo, hi = stat["ci95"]
    return f"{stat['value']:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]"


def markdown_table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(map(str, row)) + " |" for row in rows])


def digits(metric):
    return 1 if metric in TABLE_METRICS else 3


def omnidocbench_table():
    metrics = [*PAGE_METRICS, *TABLE_METRICS]
    rows = []
    for path in sorted(RESULTS.glob("E-*/stats.json")):
        stats = json.loads(path.read_text())
        exp = path.parent.name
        rows.append([exp, LABELS.get(exp, ""), stats["reading_order"]["n"], *(interval_cell(stats[m], digits(m)) for m in metrics)])
    return markdown_table(["Exp", "What", "Pages", *(METRIC_NAMES[m] for m in metrics)], rows)


def diff_table():
    metrics = [*PAGE_METRICS, *TABLE_METRICS]
    rows = []
    for path in sorted(RESULTS.glob("E-*/diff_vs_*.json")):
        stats = json.loads(path.read_text())
        rows.append([f"{path.parent.name} minus {path.stem.removeprefix('diff_vs_')}",
                     *(interval_cell(stats[m], 4 if m in PAGE_METRICS else 2) for m in metrics)])
    return markdown_table(["Change", *(METRIC_NAMES[m] for m in metrics)], rows)


def by_bucket(rows):
    groups = defaultdict(list)
    for row in rows:
        groups[int(row["pages"])].append(row)

    def mean(group, key):
        return statistics.mean(float(r[key]) for r in group if r[key] != "")

    return [{
        "pages": pages, "docs": len(group),
        "edit_distance": round(mean(group, "edit_distance"), 4), "word_recall": round(mean(group, "word_recall"), 4),
        "shifted": sum(r["pages_out"] != r["pages"] for r in group),
        "distinct_20": round(mean(group, "distinct_20"), 4), "distinct_35": round(mean(group, "distinct_35"), 4),
        "gen_tokens": round(mean(group, "gen_tokens")), "model_s": round(mean(group, "model_s"), 1),
        "peak_mlx_gb": round(max(float(r["peak_mlx_gb"]) for r in group), 2),
        "incomplete": sum(r["complete"] != "True" for r in group),
    } for pages, group in sorted(groups.items())]


def long_doc_tables():
    out = []
    for path in sorted(RESULTS.glob("E-*/scores.csv")):
        with path.open() as f:
            buckets = by_bucket(list(csv.DictReader(f)))
        out.append(f"### {path.parent.name}\n\n" + markdown_table(
            ["Pages", "Docs", "Edit distance", "Word recall", "Page count off", "Distinct-20", "Distinct-35", "Output tokens", "Model s", "Peak GB", "Incomplete"],
            [list(b.values()) for b in buckets]))
    return "\n\n".join(out)


def main():
    text = "\n\n".join([
        "# Tables\n\nGenerated by `make_tables.py` from `results/`. Do not edit by hand.",
        "## OmniDocBench v1.6 subsets\n\nEdit metrics reweighted to the full set's type mix; table scores are page averages. 95% bootstrap intervals.\n\n" + omnidocbench_table(),
        "## Paired differences (after minus before, same pages)\n\n" + diff_table(),
        "## Long documents (means per page-count bucket)\n\n" + long_doc_tables(),
    ])
    (ROOT / "docs" / "tables.md").write_text(text + "\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
